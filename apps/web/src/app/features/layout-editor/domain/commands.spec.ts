import {
  addObject,
  duplicateObject,
  moveObject,
  nextCode,
  removeObject,
  resizeObject,
  rotate90,
  updateProps,
  type EditContext,
} from './commands';
import { fromPolygon, toPolygon } from './geometry';
import type { LayoutObjectDto, LayoutObjectKind, Rect } from './layout.types';

const ctx: EditContext = { bounds: { widthM: 100, heightM: 60 }, step: 0.5 };

function obj(
  id: string,
  rect: Rect,
  kind: LayoutObjectKind = 'STAND',
  code: string | null = id,
): LayoutObjectDto {
  return { id, kind, code, geometry: toPolygon(rect), metadata: {} };
}

function rectOf(objects: readonly LayoutObjectDto[], id: string): Rect | null {
  const found = objects.find((o) => o.id === id);
  return found ? fromPolygon(found.geometry) : null;
}

function deepFreeze<T>(value: T): T {
  if (value && typeof value === 'object') {
    Object.values(value).forEach(deepFreeze);
    Object.freeze(value);
  }
  return value;
}

const pentagon: LayoutObjectDto = {
  id: 'P',
  kind: 'OBSTACLE',
  code: null,
  geometry: {
    type: 'Polygon',
    coordinates: [
      [
        [0, 0],
        [4, 0],
        [5, 3],
        [2, 5],
        [-1, 3],
        [0, 0],
      ],
    ],
  },
  metadata: {},
};

describe('nextCode', () => {
  it('returns the next free number for a prefix, zero padded', () => {
    const objects = [
      obj('a', { x: 0, y: 0, w: 1, h: 1 }, 'STAND', 'A01'),
      obj('b', { x: 2, y: 0, w: 1, h: 1 }, 'STAND', 'A07'),
    ];
    expect(nextCode(objects, 'A')).toBe('A08');
    expect(nextCode(objects, 'B')).toBe('B01');
  });
});

describe('addObject', () => {
  it('adds a 3x3 stand with an autogenerated code, snapped and clamped', () => {
    const result = addObject([], 'STAND', { x: 99.2, y: 10.3 }, ctx, 'new');
    expect(result).toHaveLength(1);
    expect(result[0]).toMatchObject({ id: 'new', kind: 'STAND', code: 'S01' });
    expect(rectOf(result, 'new')).toEqual({ x: 97, y: 10.5, w: 3, h: 3 });
  });

  it('adds non-stand objects without code', () => {
    const result = addObject([], 'AISLE', { x: 0, y: 0 }, ctx, 'aisle');
    expect(result[0].code).toBeNull();
  });
});

describe('moveObject', () => {
  it('snaps the target position (spec: "Snap al mover")', () => {
    const result = moveObject(
      [obj('A01', { x: 0, y: 0, w: 3, h: 3 })],
      'A01',
      { x: 10.37, y: 4.1 },
      ctx,
    );
    expect(rectOf(result, 'A01')).toEqual({ x: 10.5, y: 4, w: 3, h: 3 });
  });

  it('clamps inside the venue (spec: "Clamp en el borde")', () => {
    const result = moveObject(
      [obj('A01', { x: 0, y: 0, w: 3, h: 3 })],
      'A01',
      { x: 99, y: 70 },
      ctx,
    );
    expect(rectOf(result, 'A01')).toEqual({ x: 97, y: 57, w: 3, h: 3 });
  });

  it('returns the same array for unknown ids', () => {
    const objects = [obj('A01', { x: 0, y: 0, w: 3, h: 3 })];
    expect(moveObject(objects, 'nope', { x: 5, y: 5 }, ctx)).toBe(objects);
  });

  it('returns the same array when the result does not change (e.g. pushing against the edge)', () => {
    const objects = [obj('A01', { x: 97, y: 0, w: 3, h: 3 })];
    expect(moveObject(objects, 'A01', { x: 98, y: 0 }, ctx)).toBe(objects);
    expect(rotate90([obj('sq', { x: 0, y: 0, w: 2, h: 2 })], 'sq', ctx)).toHaveLength(1);
  });
});

describe('resizeObject', () => {
  const objects = [obj('A01', { x: 10, y: 10, w: 3, h: 3 })];

  it('moves the east edge', () => {
    expect(rectOf(resizeObject(objects, 'A01', 'e', { x: 15.2, y: 0 }, ctx), 'A01')).toEqual({
      x: 10,
      y: 10,
      w: 5,
      h: 3,
    });
  });

  it('moves the north-west corner keeping the opposite corner fixed', () => {
    expect(rectOf(resizeObject(objects, 'A01', 'nw', { x: 8, y: 9 }, ctx), 'A01')).toEqual({
      x: 8,
      y: 9,
      w: 5,
      h: 4,
    });
  });

  it('never shrinks below one snap step', () => {
    expect(rectOf(resizeObject(objects, 'A01', 'w', { x: 20, y: 0 }, ctx), 'A01')).toEqual({
      x: 12.5,
      y: 10,
      w: 0.5,
      h: 3,
    });
  });

  it('never grows past the venue', () => {
    expect(rectOf(resizeObject(objects, 'A01', 'se', { x: 150, y: 80 }, ctx), 'A01')).toEqual({
      x: 10,
      y: 10,
      w: 90,
      h: 50,
    });
  });
});

describe('rotate90', () => {
  it('swaps width and depth around the center (spec: "Rotar mantiene el centro")', () => {
    const result = rotate90([obj('A01', { x: 9, y: 8, w: 2, h: 4 })], 'A01', ctx);
    expect(rectOf(result, 'A01')).toEqual({ x: 8, y: 9, w: 4, h: 2 });
  });

  it('re-clamps when the rotated rect would leave the venue', () => {
    const result = rotate90([obj('A01', { x: 99, y: 0, w: 1, h: 6 })], 'A01', ctx);
    expect(rectOf(result, 'A01')).toEqual({ x: 94, y: 2.5, w: 6, h: 1 });
  });
});

describe('duplicateObject', () => {
  it('places the copy next to the source with a unique code (spec: "Duplicar genera código único")', () => {
    const objects = [
      obj('a1', { x: 0, y: 0, w: 3, h: 3 }, 'STAND', 'A01'),
      obj('a2', { x: 10, y: 0, w: 3, h: 3 }, 'STAND', 'A02'),
    ];
    const result = duplicateObject(objects, 'a1', ctx, 'copy');
    expect(result).toHaveLength(3);
    expect(result[2]).toMatchObject({ id: 'copy', kind: 'STAND', code: 'A03' });
    expect(rectOf(result, 'copy')).toEqual({ x: 3, y: 0, w: 3, h: 3 });
  });

  it('keeps code null for non-stand objects', () => {
    const result = duplicateObject(
      [obj('x', { x: 0, y: 0, w: 2, h: 2 }, 'UTILITY', null)],
      'x',
      ctx,
      'copy',
    );
    expect(result[1].code).toBeNull();
  });
});

describe('removeObject', () => {
  it('removes by id', () => {
    const objects = [
      obj('A01', { x: 0, y: 0, w: 3, h: 3 }),
      obj('A02', { x: 5, y: 0, w: 3, h: 3 }),
    ];
    expect(removeObject(objects, 'A01').map((o) => o.id)).toEqual(['A02']);
  });
});

describe('updateProps', () => {
  const objects = [obj('a', { x: 10, y: 10, w: 3, h: 3 }, 'STAND', 'A01')];

  it('updates code (trimmed) and geometry', () => {
    const result = updateProps(objects, 'a', { code: '  B05 ', w: 4.333, x: 99 }, ctx);
    expect(result[0].code).toBe('B05');
    expect(rectOf(result, 'a')).toEqual({ x: 95.67, y: 10, w: 4.33, h: 3 });
  });

  it('turns an empty code into null', () => {
    expect(updateProps(objects, 'a', { code: '   ' }, ctx)[0].code).toBeNull();
  });

  it('enforces a minimum size of one snap step', () => {
    expect(rectOf(updateProps(objects, 'a', { w: 0, h: -2 }, ctx), 'a')).toEqual({
      x: 10,
      y: 10,
      w: 0.5,
      h: 0.5,
    });
  });

  it('assigns a code when an object becomes a stand', () => {
    const aisle = [obj('x', { x: 0, y: 0, w: 2, h: 2 }, 'AISLE', null)];
    expect(updateProps(aisle, 'x', { kind: 'STAND' }, ctx)[0]).toMatchObject({
      kind: 'STAND',
      code: 'S01',
    });
  });
});

describe('non-rectangular objects', () => {
  const objects = [pentagon];

  it('ignore geometric commands', () => {
    expect(moveObject(objects, 'P', { x: 10, y: 10 }, ctx)).toBe(objects);
    expect(resizeObject(objects, 'P', 'e', { x: 10, y: 0 }, ctx)).toBe(objects);
    expect(rotate90(objects, 'P', ctx)).toBe(objects);
    expect(updateProps(objects, 'P', { x: 10 }, ctx)).toBe(objects);
  });

  it('still allow non-geometric props', () => {
    expect(updateProps(objects, 'P', { kind: 'UTILITY' }, ctx)[0].geometry).toBe(pentagon.geometry);
  });
});

describe('immutability', () => {
  it('no command mutates its input', () => {
    const objects = deepFreeze([obj('a', { x: 10, y: 10, w: 3, h: 3 }, 'STAND', 'A01')]);
    expect(() => {
      addObject(objects, 'STAND', { x: 0, y: 0 }, ctx, 'n');
      moveObject(objects, 'a', { x: 0, y: 0 }, ctx);
      resizeObject(objects, 'a', 'se', { x: 20, y: 20 }, ctx);
      rotate90(objects, 'a', ctx);
      duplicateObject(objects, 'a', ctx, 'c');
      removeObject(objects, 'a');
      updateProps(objects, 'a', { code: 'Z', w: 5 }, ctx);
    }).not.toThrow();
    expect(rectOf(objects, 'a')).toEqual({ x: 10, y: 10, w: 3, h: 3 });
  });
});
